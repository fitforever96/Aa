// End-to-end smoke test on an iPhone-sized viewport: node scripts/e2e.cjs
const { chromium, devices } = require("playwright");
const out = process.argv[2] || "tmp-qa/e2e";
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 15 Pro"], acceptDownloads: true });
  const p = await ctx.newPage();
  const errors = [];
  p.on("dialog", (d) => { console.log("DIALOG:", d.message().slice(0, 120)); d.accept(); });
  p.on("pageerror", (e) => errors.push("pageerror: " + e.message));
  p.on("console", (m) => m.type() === "error" && errors.push("console: " + m.text()));
  const base = process.env.E2E_BASE || "http://localhost:3100";
  const shot = (n) => p.screenshot({ path: `${out}/${n}.png` });
  await p.goto(base + "/");
  await p.waitForSelector("button:has-text('New Proposal')");
  await p.waitForTimeout(600);
  await shot("01-dashboard");
  await p.goto(base + "/new?mode=voice");
  await p.fill("textarea", "New proposal for a 250,000-square-foot distribution warehouse. We have mice around the loading docks and office entrances. I want 35 exterior bait stations, 50 Tin Cats, and weekly service. Give me the labor estimate and recommend pricing.");
  await p.click("text=Extract details");
  await p.waitForSelector("text=Create proposal & show estimate");
  await shot("02-intake");
  await p.click("text=Create proposal & show estimate");
  await p.waitForURL(/proposal\?id=/);
  await p.waitForSelector("text=Confirmed device labor");
  await p.waitForTimeout(500);
  await shot("03-labor");
  const deviceLabor = await p.locator("text=Confirmed device labor").locator("xpath=..").innerText();
  console.log("DEVICE:", deviceLabor.replace(/\n/g, " | "));
  await p.click("button:has-text('Pricing')");
  await p.waitForSelector("text=Manual final price");
  await p.locator("input[placeholder]").filter({ hasText: "" }).first();
  const manual = p.locator("label:has-text('Manual final price') input").first();
  await manual.fill("325.00");
  await p.click("button:has-text('Lock')");
  await p.waitForTimeout(400);
  await shot("04-pricing");
  await p.click("nav[aria-label='Proposal steps'] >> text=Customer");
  await p.locator("label:has-text('Customer name') input").fill("Midwest Logistics Partners");
  await p.locator("label:has-text('Property name') input").fill("Bentonville Distribution Center");
  await p.locator("label:has-text('Street address') input").fill("1200 Sample Logistics Way");
  await p.locator("label:has-text('City') input").fill("Bentonville");
  await p.locator("label:has-text('Contact') input").first().fill("Dana Whitfield");
  await p.click("nav[aria-label='Proposal steps'] >> text=Document");
  await p.click("button:has-text('Generate document')");
  await p.waitForTimeout(500);
  await shot("05-document");
  await p.click("nav[aria-label='Proposal steps'] >> text=Review");
  await p.click("button:has-text('Generate PDF')");
  await p.waitForSelector("img[alt='Page 1']", { timeout: 90000 });
  await p.waitForTimeout(800);
  await shot("06-review");
  const qc = await p.locator("text=Rendered PDF inspection").count();
  console.log("visual QA group shown:", qc);
  console.log("QC FAILS:", (await p.locator("svg.text-red + div .text-\\[14px\\]").allInnerTexts()).join(" | "));
  const [dl] = await Promise.all([p.waitForEvent("download"), p.click("button:has-text('Download')")]);
  await dl.saveAs(`${out}/exported.pdf`);
  console.log("downloaded", await dl.suggestedFilename());
  // persistence across reload
  await p.reload();
  await p.waitForSelector("text=Midwest Logistics Partners");
  console.log("persisted after reload: yes");
  await p.goto(base + "/knowledge?tab=assumptions");
  await p.waitForSelector("text=Confirmed standards");
  await shot("07-knowledge");
  await p.goto(base + "/settings");
  await p.waitForSelector("text=Backup & restore");
  await shot("08-settings");
  await p.setViewportSize({ width: 852, height: 393 });
  await p.goto(base + "/library");
  await p.waitForTimeout(500);
  await shot("09-landscape-library");
  console.log("ERRORS:", errors.length ? errors.join("\n") : "none");
  await b.close();
})().catch((e) => { console.error("E2E FAILED", e); process.exit(1); });
