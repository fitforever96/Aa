export type FrequencyKind =
  | "one_time"
  | "weekly"
  | "biweekly" // every two weeks — 26 visits/yr
  | "twice_monthly" // two visits per calendar month — 24 visits/yr
  | "monthly"
  | "bimonthly" // every other month
  | "quarterly"
  | "semiannual"
  | "annual"
  | "five_day_weekly" // five days per week intensive program
  | "seasonal"
  | "custom";

export interface FrequencySpec {
  kind: FrequencyKind;
  /** Seasonal: active months 1–12. */
  seasonalMonths?: number[];
  /** Seasonal: cadence inside the active months. */
  seasonalBase?: "weekly" | "biweekly" | "twice_monthly" | "monthly";
  /** Custom: visits per year (takes precedence) or interval in days. */
  customVisitsPerYear?: number;
  customIntervalDays?: number;
  customLabel?: string;
}

export type BillingMethod = "per_visit" | "fixed_monthly" | "one_time";

export interface BillingSpec {
  method: BillingMethod;
  /** Fixed-monthly billing requires explicit approval before it is presented. */
  fixedMonthlyApproved: boolean;
  /** Optional free-text billing terms shown to the customer. */
  terms: string;
}

export type DeviceLocation = "interior" | "exterior";

